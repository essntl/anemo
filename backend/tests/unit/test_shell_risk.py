RANK = {"safe": 0, "moderate": 1, "dangerous": 2}


@pytest.mark.parametrize("command", SAFE)
def test_safe_commands_are_not_flagged(command: str) -> None:
    r = classify(command)
    assert r.risk == "safe", (command, r.reasons)


@pytest.mark.parametrize("command", MODERATE)
def test_moderate_commands(command: str) -> None:
    r = classify(command)
    assert r.risk == "moderate", (command, r.risk, r.reasons)


@pytest.mark.parametrize("command", DANGEROUS)
def test_dangerous_commands_are_never_downgraded(command: str) -> None:
    r = classify(command)
    expected = "moderate" if command == "rm -- -rf" else "dangerous"
    assert RANK[r.risk] >= RANK[expected], (command, r.risk, r.reasons)
    assert r.reasons, command  # always explainable in the approval card


def test_reasons_are_human_readable() -> None:
    r = classify("git push --force && rm -rf build")
    assert r.risk == "dangerous"
    assert any("push" in x for x in r.reasons) and any("recursively" in x for x in r.reasons)
