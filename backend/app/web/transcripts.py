"""Transcripts of online videos: what is said in a video, with timestamps.

Read with yt-dlp, from the video's own subtitle tracks: one a person wrote when there
is one, else the automatically generated one. Nothing is downloaded but the video's
metadata and one subtitle file.

yt-dlp does its own HTTP, so it does not go through web/safe_http. To keep an
agent-chosen address from reaching the user's network, only the sites in SITES are
accepted (by host name, before anything is requested) and only their extractors are
enabled: yt-dlp's generic extractor, which would fetch any address, is off.

This runs in the worker, on the Anemo host. YouTube blocks or rate-limits some servers;
that is reported as `blocked`, so the caller can fall back to the user's own browser
(Anemo Companion, see docs/companion-contracts.md).
"""

import asyncio
import hashlib
import json
import logging
import re
from dataclasses import asdict, dataclass, field
from typing import Any, Literal
from urllib.parse import urlsplit

from redis.exceptions import RedisError

from app.core.redis import get_redis

log = logging.getLogger(__name__)

# Host (and its subdomains) -> the yt-dlp extractors allowed for it.
SITES: dict[str, tuple[str, ...]] = {
    "youtube.com": ("youtube", "youtube:clip"),
    "youtu.be": ("youtube",),
    "youtube-nocookie.com": ("youtube",),
    "vimeo.com": ("vimeo",),
    "dailymotion.com": ("dailymotion",),
    "ted.com": ("tedtalk",),
}
YOUTUBE_HOSTS = ("youtube.com", "youtu.be", "youtube-nocookie.com")
SOCKET_TIMEOUT_S = 20
MAX_TRACK_BYTES = 8 * 1024 * 1024
CACHE_S = 60 * 60  # a long transcript is read in several calls
Kind = Literal["manual", "auto"]
Problem = Literal["unsupported", "no_captions", "unavailable", "blocked", "failed"]


class TranscriptError(Exception):
    def __init__(self, problem: Problem, message: str) -> None:
        super().__init__(message)
        self.problem = problem
        self.message = message


@dataclass
class Segment:
    start: float  # seconds from the start of the video
    text: str


@dataclass
class Transcript:
    url: str
    title: str
    channel: str
    duration_s: int | None
    upload_date: str | None  # YYYY-MM-DD
    language: str  # the track's language code, e.g. "en"
    kind: Kind  # manual: written by a person; auto: generated by the site
    segments: list[Segment] = field(default_factory=list)


def site_of(url: str) -> str | None:
    """The supported site a URL belongs to (a key of SITES), or None."""
    host = (urlsplit(url).hostname or "").lower().rstrip(".")
    for site in SITES:
        if host == site or host.endswith("." + site):
            return site
    return None


def is_youtube(url: str) -> bool:
    return site_of(url) in YOUTUBE_HOSTS


def clock(seconds: float) -> str:
    """12.3 → "00:12"; past an hour "1:02:03"."""
    total = max(0, int(seconds))
    h, rest = divmod(total, 3600)
    m, s = divmod(rest, 60)
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m:02d}:{s:02d}"


# -- subtitle files -------------------------------------------------------------------------


def _clean(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace("\u200b", "")).strip()


def parse_json3(data: bytes) -> list[Segment]:
    """YouTube's own caption format: events with a start time and pieces of text."""
    try:
        events = json.loads(data).get("events") or []
    except (ValueError, AttributeError) as exc:
        raise TranscriptError("failed", "The site's caption file could not be read.") from exc
    segments: list[Segment] = []
    for event in events:
        if not isinstance(event, dict):
            continue
        text = _clean("".join(str(s.get("utf8", "")) for s in event.get("segs") or []))
        if text:
            segments.append(Segment(start=float(event.get("tStartMs") or 0) / 1000, text=text))
    return segments


_CUE = re.compile(r"^(?:(\d+):)?(\d{1,2}):(\d{2})[.,](\d{3})\s+-->")
_TAG = re.compile(r"<[^>]+>")


def parse_vtt(data: bytes) -> list[Segment]:
    """WebVTT (and SRT, which has the same cue lines). Automatic captions repeat the line
    before in every cue (they scroll); a repeated line is kept once."""
    segments: list[Segment] = []
    start: float | None = None
    lines: list[str] = []
    seen_before: list[str] = []

    def flush() -> None:
        nonlocal seen_before
        fresh = [line for line in lines if line not in seen_before]
        if start is not None and fresh:
            segments.append(Segment(start=start, text=" ".join(fresh)))
        if lines:
            seen_before = list(lines)

    for raw in data.decode("utf-8", errors="replace").splitlines():
        cue = _CUE.match(raw.strip())
        if cue:
            flush()
            h, m, s, ms = (int(g or 0) for g in cue.groups())
            start, lines = h * 3600 + m * 60 + s + ms / 1000, []
        elif start is not None:
            text = _clean(_TAG.sub("", raw))
            if text and not text.isdigit():  # an SRT cue number
                lines.append(text)
    flush()
    return segments


_PARSERS = {"json3": parse_json3, "vtt": parse_vtt, "srt": parse_vtt}

# -- choosing a track -----------------------------------------------------------------------


def _matching(tracks: dict[str, Any], wanted: str) -> str | None:
    """The track key for a language: exact, or a regional form ("en" → "en-US")."""
    wanted = wanted.lower()
    keys = {k.lower(): k for k in tracks}
    if wanted in keys:
        return keys[wanted]
    base = wanted.split("-")[0]
    for lower, key in keys.items():
        if lower.split("-")[0] == base and not lower.endswith("-orig"):
            return key
    return None


def choose_track(info: dict[str, Any], lang: str | None) -> tuple[str, Kind, list[dict[str, Any]]]:
    """(language, kind, formats). A track someone wrote before an automatic one. Without
    `lang`: the video's own language, then English, then whatever there is."""
    manual = {k: v for k, v in (info.get("subtitles") or {}).items() if v and k != "live_chat"}
    auto = {k: v for k, v in (info.get("automatic_captions") or {}).items() if v}
    own = str(info.get("language") or "").lower() or None
    if lang:
        for tracks, kind in ((manual, "manual"), (auto, "auto")):
            key = _matching(tracks, lang)
            if key:
                return key, kind, tracks[key]  # type: ignore[return-value]
        have = sorted({*manual, *(k for k in auto if k.endswith("-orig"))}) or sorted(auto)[:20]
        raise TranscriptError(
            "no_captions",
            f"This video has no captions in '{lang}'. "
            + (f"Available: {', '.join(have)}." if have else "It has no captions at all."),
        )
    for wanted in (own, "en"):
        key = _matching(manual, wanted) if wanted else None
        if key:
            return key, "manual", manual[key]
    if manual:
        key = next(iter(manual))
        return key, "manual", manual[key]
    # Automatic: the spoken language's track ("en-orig"), not a machine translation of it.
    originals = [k for k in auto if k.endswith("-orig")]
    for key in [*originals, *filter(None, [_matching(auto, own) if own else None, "en"])]:
        if key in auto:
            return key.removesuffix("-orig"), "auto", auto[key]
    if auto:
        key = next(iter(auto))
        return key, "auto", auto[key]
    raise TranscriptError("no_captions", "This video has no captions, so there is no transcript.")


# -- yt-dlp -----------------------------------------------------------------------------------

_BLOCKED = ("not a bot", "429", "too many requests", "rate-limit", "rate limit", "403", "captcha")
_UNAVAILABLE = (
    "private video", "video unavailable", "confirm your age", "age-restricted",
    "age restricted", "members-only", "has been removed", "not available", "sign in",
    "login required", "premium", "geo-restricted", "geo restricted", "in your country",
)  # fmt: skip


class _Quiet:
    def debug(self, msg: str) -> None: ...
    def info(self, msg: str) -> None: ...
    def warning(self, msg: str) -> None: ...
    def error(self, msg: str) -> None: ...


def _problem(exc: Exception) -> TranscriptError:
    text = re.sub(r"^ERROR:\s*", "", str(exc)).split("; please report")[0].strip()[:300]
    lowered = text.lower()
    if "unsupported url" in lowered:
        return TranscriptError("unsupported", "That address is not a video this tool can read.")
    if any(word in lowered for word in _BLOCKED):
        return TranscriptError(
            "blocked", f"The site refused the request from Anemo's server (blocked): {text}"
        )
    if any(word in lowered for word in _UNAVAILABLE):
        return TranscriptError("unavailable", f"The video is not available: {text}")
    return TranscriptError("failed", f"The transcript could not be read: {text}")


def _download(url: str, site: str, lang: str | None) -> Transcript:
    """Blocking: runs in a thread."""
    import yt_dlp  # slow to import (a thousand extractors), and only the worker needs it

    options = {
        "skip_download": True,
        "quiet": True,
        "no_warnings": True,
        "noplaylist": True,
        "socket_timeout": SOCKET_TIMEOUT_S,
        "retries": 1,
        "extractor_retries": 1,
        "allowed_extractors": list(SITES[site]),
        "ignore_no_formats_error": True,  # only the captions are wanted
        "cachedir": False,
        "logger": _Quiet(),
    }
    try:
        with yt_dlp.YoutubeDL(options) as ydl:
            info = ydl.extract_info(url, download=False)
            if not isinstance(info, dict) or info.get("_type") == "playlist" or "entries" in info:
                raise TranscriptError(
                    "unsupported", "That is a playlist or channel; give the link of one video."
                )
            language, kind, formats = choose_track(info, lang)
            chosen = next(
                (f for ext in _PARSERS for f in formats if f.get("ext") == ext and f.get("url")),
                None,
            )
            if chosen is None:
                raise TranscriptError(
                    "failed", "The video's captions are in a format this tool cannot read."
                )
            with ydl.urlopen(chosen["url"]) as response:
                data = response.read(MAX_TRACK_BYTES + 1)
    except TranscriptError:
        raise
    except Exception as exc:  # noqa: BLE001 - yt-dlp raises many kinds; all become a message
        raise _problem(exc) from exc
    if len(data) > MAX_TRACK_BYTES:
        raise TranscriptError("failed", "The video's caption file is too large.")
    segments = _PARSERS[chosen["ext"]](data)
    if not segments:
        # An empty file where captions should be is how a blocked request often looks.
        raise TranscriptError("blocked", "The site returned an empty caption file (blocked?).")
    day = str(info.get("upload_date") or "")
    return Transcript(
        url=str(info.get("webpage_url") or url),
        title=str(info.get("title") or ""),
        channel=str(info.get("channel") or info.get("uploader") or ""),
        duration_s=int(info["duration"]) if info.get("duration") else None,
        upload_date=f"{day[:4]}-{day[4:6]}-{day[6:8]}" if len(day) == 8 else None,
        language=language,
        kind=kind,
        segments=segments,
    )


def _cache_key(url: str, lang: str | None) -> str:
    digest = hashlib.sha256(f"{url}\n{lang or ''}".encode()).hexdigest()[:32]
    return f"transcript:{digest}"


def from_json(data: dict[str, Any]) -> Transcript:
    """A transcript from its JSON form (the cache, or the extension's answer)."""
    segments = [
        Segment(start=float(s.get("start") or 0), text=_clean(str(s.get("text") or "")))
        for s in data.get("segments") or []
        if isinstance(s, dict)
    ]
    duration = data.get("duration_s")
    return Transcript(
        url=str(data.get("url") or ""),
        title=str(data.get("title") or "")[:300],
        channel=str(data.get("channel") or "")[:200],
        duration_s=int(duration) if isinstance(duration, int | float) and duration > 0 else None,
        upload_date=str(data["upload_date"])[:10] if data.get("upload_date") else None,
        language=str(data.get("language") or "")[:20],
        kind="manual" if data.get("kind") == "manual" else "auto",
        segments=[s for s in segments if s.text],
    )


async def cached(url: str, lang: str | None) -> Transcript | None:
    try:
        raw = await get_redis().get(_cache_key(url, lang))
        return from_json(json.loads(raw)) if raw else None
    except (RedisError, OSError, ValueError):
        return None


async def remember(url: str, lang: str | None, transcript: Transcript) -> None:
    try:
        await get_redis().set(_cache_key(url, lang), json.dumps(asdict(transcript)), ex=CACHE_S)
    except (RedisError, OSError):
        log.warning("transcript not cached")


async def fetch(url: str, lang: str | None = None) -> Transcript:
    """The transcript of the video at `url`, from the site itself. Raises TranscriptError."""
    site = site_of(url)
    if site is None:
        raise TranscriptError(
            "unsupported",
            "Transcripts are read from YouTube, Vimeo, Dailymotion and TED links only.",
        )
    return await asyncio.to_thread(_download, url, site, lang)
